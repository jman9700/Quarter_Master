package io.github.jman9700.quartermaster.protocol

import kotlinx.serialization.Serializable

/**
 * The sync protocol between the Quarter Master app and a self-hosted server.
 * Compiled into both the client and the server, so the two can't drift apart.
 *
 * Authentication is three layers, all without central accounts:
 *  - **Device**: [Headers.DEVICE_ID] + [Headers.DEVICE_SECRET] on every request. The host whitelists devices.
 *  - **Pass**: `Authorization: Bearer <token>` from [PassResponse], valid 24 hours, for one inventory.
 *  - **Owner**: [Headers.OWNER_KEY] for changing an inventory's password or deleting it.
 */
object Api {
    const val PROTOCOL_VERSION = 1
    const val PREFIX = "/api/v1"
    const val DEFAULT_PORT = 47821

    /** UDP port the server listens on for LAN discovery (same number as HTTP, different protocol). */
    const val DISCOVERY_PORT = 47821
    const val DISCOVERY_REQUEST = "QUARTERMASTER_DISCOVER_V1"

    const val PASS_HOURS = 24

    /** Product photo file names: generated by the app, never paths. */
    val IMAGE_NAME = Regex("""[A-Za-z0-9-]{1,64}\.jpg""")
}

object Headers {
    const val DEVICE_ID = "X-QM-Device-Id"
    const val DEVICE_SECRET = "X-QM-Device-Secret"
    const val OWNER_KEY = "X-QM-Owner-Key"
}

/** Machine-readable error codes in [ApiError.code]. */
object ErrorCodes {
    const val BAD_REQUEST = "bad_request"
    const val UNKNOWN_DEVICE = "unknown_device"
    const val DEVICE_PENDING = "device_pending"
    const val DEVICE_DENIED = "device_denied"
    const val DEVICE_REVOKED = "device_revoked"
    const val WRONG_PASSWORD = "wrong_password"
    const val TOO_MANY_ATTEMPTS = "too_many_attempts"
    const val PASS_REQUIRED = "pass_required"
    const val PASS_EXPIRED = "pass_expired"
    const val WRONG_OWNER_KEY = "wrong_owner_key"
    const val NOT_FOUND = "not_found"
    const val ADMIN_ONLY = "admin_only"
}

@Serializable
data class ApiError(val code: String, val message: String, val retryAfterSeconds: Long? = null)

@Serializable
data class ServerInfo(
    val name: String,
    val version: String,
    /** Git commit the server was built from; the deploy pipeline waits for this to match. */
    val commit: String,
    val protocolVersion: Int = Api.PROTOCOL_VERSION,
    /** Port of the HTTP API; filled in discovery replies so the app knows where to connect. */
    val port: Int = Api.DEFAULT_PORT,
)

// ---- Devices and the whitelist --------------------------------------------------------------

@Serializable
enum class DeviceStatus { PENDING, APPROVED, DENIED, REVOKED }

/** Asking the host to whitelist this device. The secret is random and stays on the device. */
@Serializable
data class AccessRequest(
    val deviceId: String,
    val deviceSecret: String,
    /** Who is asking, e.g. "Jordan". The host can correct it; the activity log uses it. */
    val personName: String,
    /** e.g. "Galaxy S24 Ultra", to help the host tell devices apart. */
    val deviceName: String,
)

@Serializable
data class DeviceStatusResponse(val status: DeviceStatus, val personName: String)

// ---- Inventories ----------------------------------------------------------------------------

@Serializable
data class InventorySummary(val id: String, val name: String, val createdBy: String)

@Serializable
data class CreateInventoryRequest(val name: String, val password: String)

@Serializable
data class CreateInventoryResponse(
    val inventory: InventorySummary,
    /** Proves ownership; shown once and kept on the creating device. */
    val ownerKey: String,
)

@Serializable
data class PassRequest(val password: String)

@Serializable
data class PassResponse(val token: String, val expiresAt: Long)

@Serializable
data class ChangePasswordRequest(val newPassword: String)

// ---- Sync -----------------------------------------------------------------------------------

/**
 * A product row, as in the app's backups. Times are epoch milliseconds, dates ISO yyyy-mm-dd.
 * [deletedAt] is a tombstone so deletions reach every device.
 */
@Serializable
data class ProductRow(
    val id: String,
    val gtin: String? = null,
    val name: String,
    val lifespanDays: Int,
    val quantity: Double,
    val unit: String,
    val imageFile: String? = null,
    val createdAt: Long,
    val updatedAt: Long,
    val deletedAt: Long? = null,
    val userFields: String = "",
    val lookupStatus: String = "NONE",
    val nutrition: String? = null,
    /** Device id of the last writer; the server sets it from the request. Breaks [Merge] ties. */
    val changedBy: String = "",
)

@Serializable
data class ItemRow(
    val id: String,
    val typeId: String,
    val addedOn: String,
    val bestBy: String? = null,
    val removedOn: String? = null,
    val removalReason: String? = null,
    val createdAt: Long,
    val updatedAt: Long,
    val deletedAt: Long? = null,
    /** Device id of the last writer; the server sets it from the request. Breaks [Merge] ties. */
    val changedBy: String = "",
)

/**
 * One round trip: the device's queued changes go up, everyone else's come back.
 * [cursor] is the highest server sequence number this device has already received (0 the first time).
 */
@Serializable
data class SyncRequest(
    val cursor: Long,
    val products: List<ProductRow> = emptyList(),
    val items: List<ItemRow> = emptyList(),
)

@Serializable
data class SyncResponse(
    /** Store this and send it next time. */
    val cursor: Long,
    /** Rows changed since the request's cursor, newest version of each, including the device's own accepted rows. */
    val products: List<ProductRow>,
    val items: List<ItemRow>,
    /** Photos referenced by products that the server doesn't have yet; upload them. */
    val missingImages: List<String>,
)

/** Last-write-wins: newer [updatedAt] wins; on a tie, the larger device id wins. Same answer on every device and the server. */
object Merge {
    fun incomingWins(incomingUpdatedAt: Long, incomingDevice: String, storedUpdatedAt: Long, storedDevice: String): Boolean =
        incomingUpdatedAt > storedUpdatedAt || (incomingUpdatedAt == storedUpdatedAt && incomingDevice > storedDevice)
}
